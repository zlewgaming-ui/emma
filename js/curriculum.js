// A2 osiągasz po dziale 15, B1 po dziale 40.
export const A2_AFTER_UNIT = 15;
export const LAST_UNIT = UNITS.length;

export function unitById(id) {
  return UNITS.find((u) => u.id === id) || UNITS[0];
}

export function programShare(unit, mastery = 0) {
  return Math.min(1, ((unit - 1) + Math.min(100, Math.max(0, mastery)) / 100) / LAST_UNIT);
}

export function levelName(unit) {
  if (unit <= A2_AFTER_UNIT) return 'w drodze do A2';
  return 'w drodze do B1';
}

// Ile polskiego, a ile angielskiego używa Emma na danym etapie.
export function languageRule(unit) {
  if (unit <= 8) return 'Wyjaśniasz po polsku, jednym lub dwoma zdaniami. Angielski tylko w przykładach, zadaniach i rozmowie.';
  if (unit <= 20) return 'Gramatykę wyjaśniasz po polsku, ale pochwały i proste polecenia dajesz po angielsku (Try again, Good, Say it again).';
  if (unit <= 32) return 'Mówisz głównie prostym angielskim. Po polsku tylko trudne wyjaśnienia gramatyki.';
  return 'Cała lekcja po angielsku. Po polsku tylko wtedy, gdy uczeń naprawdę utknie.';
}

// Domyślne tempo angielskiego głosu: na początku wolniej, potem normalnie.
export function defaultEnglishRate(unit) {
  if (unit <= 8) return 0.8;
  if (unit <= 20) return 0.88;
  if (unit <= 32) return 0.95;
  return 1;
}
